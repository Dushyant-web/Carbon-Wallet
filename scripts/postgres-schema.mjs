/**
 * Writes prisma/postgres/schema.prisma from prisma/schema.prisma for Supabase (Postgres).
 * The models are identical; only the datasource changes (pooled DATABASE_URL for the app, DIRECT_URL for
 * migrations) and a second client is generated for the one-off SQLite → Postgres copy.
 *   node scripts/postgres-schema.mjs
 */
import { readFileSync, writeFileSync } from "fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src
  .replace(
    /generator client \{[^}]*\}/,
    `generator client {\n  provider      = "prisma-client-js"\n  binaryTargets = ["native", "rhel-openssl-3.0.x"] // Netlify functions run on Amazon Linux\n}\n\n// used only by scripts/sqlite-to-postgres.ts\ngenerator pgcopy {\n  provider = "prisma-client-js"\n  output   = "./client"\n}`,
  )
  .replace(
    /datasource db \{[^}]*\}/,
    `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}`,
  );
writeFileSync(
  "prisma/postgres/schema.prisma",
  `// GENERATED by scripts/postgres-schema.mjs from prisma/schema.prisma. Do not edit by hand.\n${out}`,
);
console.log("wrote prisma/postgres/schema.prisma");
